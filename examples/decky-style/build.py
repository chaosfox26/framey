"""Package the shared source adapter with this example; no npm is required."""

from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def bundle():
    helper = (ROOT / "compat" / "decky-source.js").read_text(encoding="utf-8")
    source = (HERE / "source.js").read_text(encoding="utf-8")
    return "// Generated by examples/decky-style/build.py; edit source.js instead.\n" + helper.rstrip() + "\n\n" + source


if __name__ == "__main__":
    (HERE / "main.js").write_text(bundle(), encoding="utf-8")
